export const STRINGS = { en, id }

/** 'auto' follows the browser/OS language; anything starting with "id" is Indonesian. */
export function resolveLanguage (setting, navigatorLanguage = 'en') {
  if (setting === 'en' || setting === 'id') return setting
  return String(navigatorLanguage || '').toLowerCase().startsWith('id') ? 'id' : 'en'
}

export function createT (language) {
  const table = STRINGS[language] ?? STRINGS.en
  return function t (key, vars = {}) {
    const entry = table[key] ?? STRINGS.en[key]
    if (entry === undefined) return key
    if (typeof entry === 'function') return entry(vars)
    return entry.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m))
  }
}
